// Every vehicle in Marazul that can be driven, ridden, sailed or flown: the 24 models the vehicle
// artists build, each with an invented make and model, the numbers the physics derives its tuning
// from, its paint colours, where it turns up and what its radio is tuned to. Plain frozen data,
// no imports.
//
// Units: metres, seconds, kilograms, radians; speeds in metres per second (the HUD multiplies by
// 3.6 to show km/h); braking in m/s^2; grip as peak lateral acceleration in g on dry asphalt;
// driftTendency from 0 (planted) to 1 (the tail leads); durability in hit points (a family sedan
// has 850); price and exportValue in whole dollars (null: not sold, not exported). Colours are
// sRGB hex paint colours. District ids come from cityDistricts.js (and must agree with each
// district's trafficMix), landmark kinds from LANDMARK_KINDS there, station ids from
// radioStations.js, brand ids from brandsAndSignage.js.

